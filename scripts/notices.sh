#!/bin/sh
# Write THIRD-PARTY-NOTICES.md: the license and notice files of every module
# linked into wdx, and of Go itself, which the BSD, MIT and Apache licenses
# ask a binary release to carry. scripts/dist.sh packs it into every archive;
# scripts/release.sh refuses to release when it is stale.
#
# A module whose license is none of those below fails it, so a new
# dependency's license is looked at before it ships.
set -eu

OUT=THIRD-PARTY-NOTICES.md

die() { printf 'error: %s\n' "$*" >&2; exit 1; }

cd "$(dirname "$0")/.."

# license names the licenses whose text is in file.
license() {
	ids=
	grep -q 'Apache License' "$1" && grep -q 'Version 2.0' "$1" && ids="$ids Apache-2.0"
	grep -q 'Permission is hereby granted, free of charge' "$1" && ids="$ids MIT"
	if grep -q 'Redistribution and use in source and binary forms' "$1"; then
		if grep -q 'Neither the name' "$1"; then ids="$ids BSD-3-Clause"; else ids="$ids BSD-2-Clause"; fi
	fi
	grep -q 'Permission to use, copy, modify, and/or distribute' "$1" && ids="$ids ISC"
	printf '%s' "${ids# }" | sed 's/ / and /g'
}

# files lists the license and notice files at the top of module directory $1.
files() {
	ls "$1" | grep -i -E '^(licen[cs]e|copying|notice|patents)' | LC_ALL=C sort
}

# section writes the heading, the license and the files of a module.
section() {
	name="$1" dir="$2"
	main="$(files "$dir" | grep -i -E '^(licen[cs]e|copying)(\.(txt|md))?$' | head -n 1)"
	[ -n "$main" ] || die "$name has no LICENSE file in $dir"
	id="$(license "$dir/$main")"
	[ -n "$id" ] || die "$name: $dir/$main is none of the licenses scripts/notices.sh knows; check it and add it there"
	printf '| `%s` | %s |\n' "$name" "$id" >>"$table"
	{
		printf '\n## %s\n' "$name"
		for f in $(files "$dir"); do
			printf '\n### %s\n\n~~~~text\n' "$f"
			sed 's/[[:space:]]*$//' "$dir/$f"
			printf '~~~~\n'
		done
	} >>"$texts"
}

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
table="$tmp/table" texts="$tmp/texts"
: >"$table"
: >"$texts"

section "Go (its standard library and runtime)" "$(go env GOROOT)"
go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}}@{{.Version}} {{.Dir}}{{end}}{{end}}' ./cmd/wdx |
	LC_ALL=C sort -u >"$tmp/modules"
while read -r module dir; do
	section "$module" "$dir"
done <"$tmp/modules"

{
	echo "# Third-party notices"
	echo
	echo "wdx (Apache-2.0, see LICENSE and NOTICE) is built with Go and the modules below,"
	echo "each the copyright of its authors. Their license and notice files follow in full."
	echo
	echo "Generated by scripts/notices.sh (\`make notices\`): do not edit."
	echo
	echo "| Module | License |"
	echo "|---|---|"
	cat "$table"
	cat "$texts"
} >"$OUT"

echo "wrote $OUT ($(wc -l <"$table" | tr -d ' ') modules)"
